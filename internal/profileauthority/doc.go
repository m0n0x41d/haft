// Package profileauthority owns the project-profile declaration institutional
// effect above the reusable manual SpeechAct source kernel.
//
// The package deliberately separates design-time authorization content, the
// actual recorded communicative Work, the resulting U.Commitment(MAY), and its
// four-ref authority basis. It does not capture terminal input and exposes no
// conversion from a recorded SpeechAct back into a completion capability.
//
// Durable phase-two persistence starts with schema v43. The v38 permission
// shape cannot represent A.2.8 carrier-class adjudication without also placing
// an actual terminal carrier occurrence in the same typed set, so this package
// must not emit a compatibility write that repeats that category error.
//
// AuthorityResolutionRecord is a later, context-local A.2.5
// EnactableStateAdmission evaluation over that existing permission. It does
// not create a second permission or durable capability. A new resolution is
// pre-Work and carries no consumable use. AdmittedUse is minted only by exact
// post-Work replay at the transaction judgement time; durable single-use
// consumption and profile admission belong to the transaction-owning
// profile-admission layer.
// AuthorityUseRecord is only the immutable historical consumption fact that
// layer commits beside the admission; it is not reusable authority.
